/**
 * Static blog catalog. SEO-targeted long-form content lives here as
 * structured data rather than MDX — it lets us render rich, typed
 * sections without an extra toolchain, and `generateStaticParams`
 * picks up new slugs automatically.
 *
 * Adding a post: append a new entry below. The sitemap reads this same
 * list, so a new slug is indexed on the next deployment.
 */

export interface BlogSection {
  heading: string;
  body: string;
}

export type BlogLocale = "ko" | "en";

export interface BlogPost {
  slug: string;
  title: string;
  excerpt: string;
  publishedAt: string;
  readingMinutes: number;
  tags: string[];
  sections: BlogSection[];
  /**
   * Language of the post. Default is "ko" for posts written without an
   * explicit value, preserving the historical Korean catalog. English posts
   * for the global rollout opt in by setting locale: "en".
   */
  locale?: BlogLocale;
}

export function postLocale(post: BlogPost): BlogLocale {
  return post.locale ?? "ko";
}

